#!/usr/bin/env node
/**
 * Builds `brand/social-preview.svg` from the copy in this file.
 *
 * The banner's text used to be laid out by hand, with a pixel width guessed for every chip. Any
 * wording change then overflowed the pill it sat in, because nothing connected the two. Every run
 * here is measured with the same renderer that draws it — `measureText()` renders the string and
 * trims it — so a pill is always its label plus padding, and the layout asserts that the row fits
 * before writing anything.
 *
 * Run via `pnpm run brand`, which also renders the PNG and the icons.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const brand = path.join(root, 'brand')

/** The 2:1 canvas GitHub asks for, and its margins. */
const WIDTH = 1280
const HEIGHT = 640
const MARGIN = 88
/** Where the text block starts: past the mark, which is `MARK_SIZE` wide from `MARGIN`. */
const MARK_SIZE = 224
const TEXT_X = MARGIN + MARK_SIZE + 56
/** The widest a text run may be before it would touch the right margin. */
const TEXT_MAX = WIDTH - MARGIN - TEXT_X

/** The stock UI's own dark-theme tokens, so the banner cannot drift from the panel. */
const COLOR = {
  page: '#0a0e14',
  panel: '#111722',
  raise: '#1a2432',
  ink: '#e8eef8',
  muted: '#93a2b8',
  faint: '#64748b',
  accent: '#6d8dff',
  ok: '#34d399',
}

const FONT = 'DejaVu Sans, Inter, Segoe UI, system-ui, sans-serif'

const TITLE = 'home-hosted'
const TAGLINE = 'Self-hosted control panel for your home server.'
/** Generic capability words, not slogans: these are read at a glance and indexed. */
const TAGS = ['Supervision', 'Health checks', 'Live logs', 'Backups']
const FOOTER_LEFT = 'github.com/NamesMT/home-hosted'
const FOOTER_RIGHT = 'Linux · macOS · Windows'

const TITLE_SIZE = 86
const TAGLINE_SIZE = 31
const TAG_SIZE = 25
const FOOTER_SIZE = 26
/** Horizontal padding inside a pill, each side. */
const TAG_PAD = 30
const TAG_GAP = 16
const TAG_HEIGHT = 54

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'hh-brand-'))

/** Escape the five characters that cannot appear raw in XML text content. */
function esc(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

/**
 * The width `text` actually renders to, in this font at this size.
 *
 * Measured rather than estimated: the advance width depends on the font that resolves on this
 * machine, so a table of numbers would drift from what is drawn. `-trim` reports what was painted.
 */
function measureText(text, size, weight = 'normal') {
  const file = path.join(tmp, 'measure')
  fs.writeFileSync(`${file}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" width="4000" height="400"><text x="0" y="300" font-family="${FONT}" font-size="${size}" font-weight="${weight}" fill="#fff">${esc(text)}</text></svg>`)
  execFileSync('rsvg-convert', [`${file}.svg`, '-o', `${file}.png`])
  const width = execFileSync('magick', [`${file}.png`, '-trim', '-format', '%w', 'info:'], { encoding: 'utf8' })
  return Number(width.trim())
}

const titleWidth = measureText(TITLE, TITLE_SIZE, 'bold')
const taglineWidth = measureText(TAGLINE, TAGLINE_SIZE)

if (titleWidth > TEXT_MAX || taglineWidth > TEXT_MAX) {
  process.stderr.write(`[brand] the banner copy is too wide: title ${titleWidth}px, tagline ${taglineWidth}px — the text column allows ${TEXT_MAX}px\n`)
  process.exit(1)
}

/** Each pill is its label plus padding, so the text can never outgrow the shape. */
const pills = TAGS.map((label) => {
  const text = measureText(label, TAG_SIZE)
  return { label, text, width: text + TAG_PAD * 2 }
})

const rowWidth = pills.reduce((total, pill) => total + pill.width, 0) + TAG_GAP * (pills.length - 1)
if (rowWidth > TEXT_MAX) {
  process.stderr.write(`[brand] the tag row is ${rowWidth}px, over the ${TEXT_MAX}px column — drop a tag or shorten one\n`)
  process.exit(1)
}

let pillX = TEXT_X
const pillMarkup = pills.map((pill) => {
  const markup = `    <rect x="${pillX}" y="392" width="${pill.width}" height="${TAG_HEIGHT}" rx="${TAG_HEIGHT / 2}" fill="${COLOR.raise}"/>\n`
    + `    <text x="${pillX + TAG_PAD}" y="${392 + TAG_HEIGHT / 2 + TAG_SIZE * 0.35}" font-size="${TAG_SIZE}" fill="#c3cfe2">${esc(pill.label)}</text>`
  pillX += pill.width + TAG_GAP
  return markup
}).join('\n')

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" role="img" aria-label="GitHub social preview banner for home-hosted">
  <title>home-hosted — GitHub social preview</title>
  <!--
    GENERATED by scripts/build-social-preview.mjs — edit that file, not this one, then run
    \`pnpm run brand\`. Every text run below was measured with the renderer, so a pill is always
    its label plus padding and the row is checked against the text column before writing.

    2:1 (1280x640), the size GitHub asks for. Left-weighted: mark, name, one line of positioning,
    then four generic capability words. The right side stays quiet because the card is usually
    shown ~500px wide in a timeline.
  -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${COLOR.page}"/>
      <stop offset="1" stop-color="${COLOR.panel}"/>
    </linearGradient>
    <linearGradient id="glow" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${COLOR.accent}" stop-opacity="0.20"/>
      <stop offset="1" stop-color="${COLOR.accent}" stop-opacity="0"/>
    </linearGradient>
  </defs>

  <rect width="${WIDTH}" height="${HEIGHT}" fill="url(#bg)"/>
  <ellipse cx="150" cy="110" rx="460" ry="320" fill="url(#glow)"/>

  <!-- The mark, from brand/logo.svg's 512 grid. The vent slots are punched in the page colour. -->
  <g transform="translate(${MARGIN} 208) scale(${(MARK_SIZE / 512).toFixed(4)})">
    <path d="M84 188 L256 64 L428 188 L428 460 L84 460 Z"
          fill="none" stroke="${COLOR.accent}" stroke-width="30" stroke-linejoin="miter" stroke-linecap="round"/>
    <g fill="${COLOR.accent}">
      <rect x="152" y="216" width="208" height="52" rx="13"/>
      <rect x="152" y="290" width="208" height="52" rx="13"/>
      <rect x="152" y="364" width="208" height="52" rx="13"/>
    </g>
    <g fill="#0d1420">
      <rect x="178" y="236" width="20" height="12" rx="4"/>
      <rect x="208" y="236" width="20" height="12" rx="4"/>
      <rect x="238" y="236" width="20" height="12" rx="4"/>
      <rect x="178" y="310" width="20" height="12" rx="4"/>
      <rect x="208" y="310" width="20" height="12" rx="4"/>
      <rect x="238" y="310" width="20" height="12" rx="4"/>
      <rect x="178" y="384" width="20" height="12" rx="4"/>
      <rect x="208" y="384" width="20" height="12" rx="4"/>
      <rect x="238" y="384" width="20" height="12" rx="4"/>
    </g>
    <circle cx="324" cy="242" r="12" fill="${COLOR.ok}"/>
  </g>

  <g font-family="${FONT}">
    <text x="${TEXT_X}" y="292" font-size="${TITLE_SIZE}" font-weight="bold" fill="${COLOR.ink}" letter-spacing="-2">${esc(TITLE)}</text>
    <text x="${TEXT_X + 4}" y="344" font-size="${TAGLINE_SIZE}" fill="${COLOR.muted}">${esc(TAGLINE)}</text>

${pillMarkup}

    <text x="${MARGIN}" y="562" font-size="${FOOTER_SIZE}" fill="${COLOR.faint}">${esc(FOOTER_LEFT)}</text>
    <text x="${WIDTH - MARGIN}" y="562" font-size="${FOOTER_SIZE}" fill="${COLOR.faint}" text-anchor="end">${esc(FOOTER_RIGHT)}</text>
  </g>
</svg>
`

fs.writeFileSync(path.join(brand, 'social-preview.svg'), svg)
fs.rmSync(tmp, { recursive: true, force: true })
process.stdout.write(`[brand] social-preview.svg: title ${titleWidth}px, tagline ${taglineWidth}px, tag row ${rowWidth}px of ${TEXT_MAX}px\n`)

// Printed so the caller can see the layout the file was built from, without opening it.
for (const pill of pills)
  process.stdout.write(`[brand]   ${pill.label}: text ${pill.text}px, pill ${pill.width}px\n`)
