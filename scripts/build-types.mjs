#!/usr/bin/env node
/**
 * Emits `dist/types/**` — the declarations `home-hosted/client` ships, so a client gets the server's
 * own route types (`AppType`) without the source tree.
 *
 * `#src/*` is this repository's import map (package.json `imports`), which points at `src/` — not in
 * the published package. Every specifier is rewritten to a relative `.js` path, which TypeScript
 * resolves to the `.d.ts` beside it under every module resolution mode.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const out = path.join(root, 'dist', 'types')

fs.rmSync(out, { recursive: true, force: true })
execFileSync(process.execPath, [path.join(root, 'node_modules', 'typescript', 'bin', 'tsc'), '-p', path.join(root, 'tsconfig.types.json')], { stdio: 'inherit' })

/** `#src/a/b` → the emitted file it names, as a path relative to `from`. */
function rewrite(specifier, from) {
  const target = path.join(out, specifier.slice('#src/'.length))
  const file = fs.existsSync(`${target}.d.ts`) ? `${target}.js` : path.join(target, 'index.js')
  if (!fs.existsSync(file.replace(/\.js$/, '.d.ts')))
    throw new Error(`[types] ${path.relative(root, from)} names ${specifier}, which emitted no declaration`)
  const relative = path.relative(path.dirname(from), file).replaceAll('\\', '/')
  return relative.startsWith('.') ? relative : `./${relative}`
}

/** Relative imports tsc kept extensionless (`./x`) get `.js` too, for node16/nodenext consumers. */
function withExtension(specifier, from) {
  if (/\.(?:js|json)$/.test(specifier))
    return specifier
  const target = path.resolve(path.dirname(from), specifier)
  return fs.existsSync(`${target}.d.ts`) ? `${specifier}.js` : `${specifier}/index.js`
}

let files = 0
for (const entry of fs.readdirSync(out, { recursive: true, withFileTypes: true })) {
  if (!entry.isFile() || !entry.name.endsWith('.d.ts'))
    continue
  const file = path.join(entry.parentPath, entry.name)
  const text = fs.readFileSync(file, 'utf8')
  const next = text.replace(/(from\s+|import\()(['"])([^'"]+)\2/g, (whole, lead, quote, specifier) => {
    if (specifier.startsWith('#src/'))
      return `${lead}${quote}${rewrite(specifier, file)}${quote}`
    if (specifier.startsWith('./') || specifier.startsWith('../'))
      return `${lead}${quote}${withExtension(specifier, file)}${quote}`
    return whole
  })
  if (next !== text)
    fs.writeFileSync(file, next)
  files += 1
}

/**
 * The declarations must not need `@types/node`.
 *
 * A consumer is a browser, a Svelte app or a Bun script: it wants `createClient`'s types, not the
 * panel's process supervision. Measured on a browser tsconfig (`"types": []`, `skipLibCheck: false`)
 * against `dist/types`, importing the client produced **8 errors** — `Cannot find name
 * 'node:buffer'` and `Cannot find namespace 'NodeJS'` — because `AppType` transitively names
 * `ChildProcess`, `Buffer`, `NodeJS.Signals` and friends. Asking an app author to install
 * `@types/node` to read a client's types is the defect; the panel's own server types should not
 * decide what a browser project installs.
 *
 * Two rewrites, both mechanical, so nothing can drift from the source:
 *   - every `node:*` type import points at the shipped `node-compat.d.ts`, which declares the handful
 *     of names the public surface actually uses;
 *   - every `NodeJS.<X>` reference keeps working, because that file declares the namespace globally.
 *
 * The names are deliberately structural (`Buffer` as a `Uint8Array`, `ChildProcess` with the members
 * the types read) and never `any`: a consumer that passes one of these to a real Node API still gets
 * a useful check, and one that never touches them sees nothing at all.
 */
const NODE_COMPAT = `/**
 * The Node types the published declarations mention, declared locally.
 *
 * Generated by \`scripts/build-types.mjs\`. This file exists so \`home-hosted/client\` can be typed in a
 * project that does not install \`@types/node\` — the panel's server-side types are an implementation
 * detail of the package, not something an app author should have to depend on.
 */

/** The parts of a Node \`Buffer\` the published types mention. A \`Uint8Array\` is what it is. */
export type Buffer = Uint8Array

/** The parts of a child process handle the published types mention. */
export interface ChildProcess {
  readonly pid?: number
  readonly exitCode: number | null
  readonly signalCode: NodeJS.Signals | null
  kill: (signal?: NodeJS.Signals | number) => boolean
}

declare global {
  // eslint-disable-next-line ts/no-namespace
  namespace NodeJS {
    interface Timeout {
      ref: () => this
      unref: () => this
      hasRef: () => boolean
      refresh: () => this
      close: () => void
      [Symbol.toPrimitive]: () => number
    }

    type Signals = string
    type Platform = string
    type ProcessEnv = Record<string, string | undefined>

    interface ErrnoException extends Error {
      errno?: number
      code?: string
      path?: string
      syscall?: string
    }
  }
}
`
fs.writeFileSync(path.join(out, 'node-compat.d.ts'), NODE_COMPAT)

/** The `node:*` specifiers the declarations import, and what each becomes. */
const NODE_IMPORT = /(['"])node:(?:buffer|child_process|events|fs|http|https|net|os|path|stream|tls|url|util|zlib|crypto)\1/g

for (const entry of fs.readdirSync(out, { recursive: true, withFileTypes: true })) {
  if (!entry.isFile() || !entry.name.endsWith('.d.ts') || entry.name === 'node-compat.d.ts')
    continue
  const file = path.join(entry.parentPath, entry.name)
  const text = fs.readFileSync(file, 'utf8')
  const rewritten = text.replace(NODE_IMPORT, (_whole, quote) => {
    const relative = path.relative(path.dirname(file), path.join(out, 'node-compat.js')).replaceAll('\\', '/')
    return `${quote}${relative.startsWith('.') ? relative : `./${relative}`}${quote}`
  })
  if (rewritten !== text)
    fs.writeFileSync(file, rewritten)
}

const leftover = fs.readdirSync(out, { recursive: true })
  .filter(name => String(name).endsWith('.d.ts'))
  .filter(name => fs.readFileSync(path.join(out, String(name)), 'utf8').includes('\'#src/'))
if (leftover.length > 0) {
  console.error(`[types] unrewritten #src specifiers in: ${leftover.join(', ')}`)
  process.exit(1)
}
console.log(`[types] ${files} declarations in dist/types`)
